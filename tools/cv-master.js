/* =========================================================================
   Master CV for the CV tailor (cv-tailor/): one clean list of everything
   that is true about you, taken from the files the site already uses:

     content/cv.js        profile, experience, education, skills, languages
     js/projects.js       projects you added by hand
     js/sheet-works.js    projects from the Works tab of the Google Sheet
     js/certificates.js   certificates (replaced by the sheet's Certificates
     js/sheet-data.js     tab when the sheet has one)

   Nothing is typed twice: tools/build-pages.js calls this and writes the
   result to js/cv-master.js, which the cv-tailor page reads. So edit the
   files above, never js/cv-master.js.

   Visibility: projects and certificates with  portfolio: false  (or "No" in
   the sheet's "Job portfolio" column) are left out completely, so they can
   never end up on a job CV by mistake. Only their number is recorded.

   Every bullet gets an id made from its own text (e.g. exp-kirdi-3f9a1c),
   so the tailor can remember your choices and an AI assistant can cite
   which real line each sentence came from. Editing a bullet gives it a new
   id; the tailor then simply treats it as a new line.
   ========================================================================= */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const C = require('../js/cv-tailor-core.js');   // the same normalizer the page uses for clients' own CVs

const SITE = 'https://edisonengineer.github.io/MY-PAST-PROJECTS/';
const SOURCES = ['content/cv.js', 'js/projects.js', 'js/sheet-works.js', 'js/certificates.js', 'js/sheet-data.js'];

function load(root) {
    const ctx = { window: {} };
    for (const f of SOURCES) {
        const file = path.join(root, f);
        if (fs.existsSync(file)) vm.runInNewContext(fs.readFileSync(file, 'utf8'), ctx, { filename: f });
    }
    return ctx.window;
}

// The website's data as a "raw" CV (the shape clients edit on the page), hidden items left out
function siteRaw(root) {
    const w = load(root);
    const cv = w.CV;
    if (!cv) throw new Error('content/cv.js did not define window.CV');
    const allProjects = w.PROJECTS || [];
    const allCerts = w.CERTIFICATES || [];
    const projects = allProjects.filter((p) => p && p.portfolio !== false);
    const certs = allCerts.filter((c) => c && c.portfolio !== false);
    // CV project blurbs can point at a full project with  id: '<project id>'  (content/cv.js)
    const blurbs = Array.isArray(cv.projects) ? cv.projects : [];
    const linked = new Map(blurbs.filter((b) => b.id).map((b) => [b.id, b]));
    const hiddenIds = new Set(allProjects.filter((p) => p && p.portfolio === false).map((p) => p.id));
    const raw = {
        person: { name: cv.name, title: cv.title, tagline: cv.tagline, location: cv.location, phone: cv.phone, email: '', linkedin: cv.linkedin, website: SITE,
            portfolio: /^https:\/\//.test(cv.portfolio || '') ? cv.portfolio : SITE },
        summary: cv.summary,
        experience: (cv.experience || []).map((x) => ({ role: x.role, org: x.org, dates: x.dates, points: x.points })),
        projects: projects.map((p) => ({
            title: p.title, subtitle: p.subtitle, year: p.year, category: p.category, source: p.id, outcome: p.outcome,
            summary: (linked.get(p.id) || p).text || p.summary, points: p.points, tags: p.tags,
            url: fs.existsSync(path.join(root, 'projects', p.id + '.html')) ? SITE + 'projects/' + p.id + '.html' : ''
        })),
        education: cv.education, skills: cv.skills, languages: cv.languages, memberships: cv.memberships,
        certificates: certs.map((c) => ({ title: c.title, issuer: c.issuer, verify: c.verify }))
    };
    // CV blurbs that don't point at a project on the site become projects of their own (unless that project is hidden)
    blurbs.filter((b) => !(b.id && (projects.some((p) => p.id === b.id) || hiddenIds.has(b.id))))
        .forEach((b) => raw.projects.push({ title: b.name, summary: b.text, source: 'content/cv.js' }));
    return { raw, hidden: { projects: allProjects.length - projects.length, certificates: allCerts.length - certs.length } };
}

function buildMaster(root) {
    const { raw, hidden } = siteRaw(root);
    return C.normalizeMaster(raw, { hidden, about: 'Generated by tools/build-pages.js from ' + SOURCES.join(', ') + '. Edit those files, not this one.' });
}

function masterJs(master) {
    return '/* Master CV for cv-tailor/: generated by tools/build-pages.js (see tools/cv-master.js).\n' +
        '   Edit content/cv.js, js/projects.js or the Google Sheet instead of this file.\n' +
        '   Projects and certificates marked portfolio: false are not in here. */\n' +
        'window.CV_MASTER = ' + JSON.stringify(master, null, 1) + ';\n';
}

module.exports = { buildMaster, masterJs, siteRaw, certKind: C.certKind, SOURCES };
