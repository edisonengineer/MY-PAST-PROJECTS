/* =========================================================================
   Master CV for the CV tailor (cv-tailor/): one clean list of everything
   that is true about you, taken from the files the site already uses:

     content/cv.js        profile, experience, education, skills, languages
     js/projects.js       projects you added by hand
     js/sheet-works.js    projects from the Works tab of the Google Sheet
     js/certificates.js   certificates (replaced by the sheet's Certificates
     js/sheet-data.js     tab when the sheet has one)

   Nothing is typed twice: tools/build-pages.js calls this and writes the
   result to js/cv-master.js, which the cv-tailor page reads. So edit the
   files above, never js/cv-master.js.

   Visibility: projects and certificates with  portfolio: false  (or "No" in
   the sheet's "Job portfolio" column) are left out completely, so they can
   never end up on a job CV by mistake. Only their number is recorded.

   Every bullet gets an id made from its own text (e.g. exp-kirdi-3f9a1c),
   so the tailor can remember your choices and an AI assistant can cite
   which real line each sentence came from. Editing a bullet gives it a new
   id; the tailor then simply treats it as a new line.
   ========================================================================= */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const SITE = 'https://edisonengineer.github.io/MY-PAST-PROJECTS/';
const SOURCES = ['content/cv.js', 'js/projects.js', 'js/sheet-works.js', 'js/certificates.js', 'js/sheet-data.js'];

const slug = (s, n = 24) => String(s || '').toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, n).replace(/-$/, '') || 'item';
const hash = (s) => crypto.createHash('sha1').update(String(s)).digest('hex').slice(0, 6);
const clean = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const lines = (arr, prefix) => (Array.isArray(arr) ? arr : []).map(clean).filter(Boolean).map((text) => ({ id: prefix + '-' + hash(text), text }));

// Latest year mentioned in a date range ("Jun – Aug 2025", "Dec 2024 – Present")
function latestYear(dates) {
    if (/present|current|now/i.test(dates || '')) return new Date().getFullYear();
    const ys = String(dates || '').match(/\b(19|20)\d{2}\b/g);
    return ys ? Math.max(...ys.map(Number)) : null;
}

// What a certificate really is, so a prep course is never presented as the certification itself
function certKind(c) {
    const t = (c.title + ' ' + (c.issuer || '')).toLowerCase();
    if (/designathon|award|honou?rable|mention|winner|finalist|participant|prize/.test(t)) return 'award';
    if (/\bprep\b|preparation|essential training|\btraining\b|\bcourse\b|bootcamp|tutorial/.test(t)) return 'course';
    return 'certification';
}

function load(root) {
    const ctx = { window: {} };
    for (const f of SOURCES) {
        const file = path.join(root, f);
        if (fs.existsSync(file)) vm.runInNewContext(fs.readFileSync(file, 'utf8'), ctx, { filename: f });
    }
    return ctx.window;
}

function buildMaster(root) {
    const w = load(root);
    const cv = w.CV;
    if (!cv) throw new Error('content/cv.js did not define window.CV');
    const allProjects = w.PROJECTS || [];
    const allCerts = w.CERTIFICATES || [];
    const projects = allProjects.filter((p) => p && p.portfolio !== false);
    const certs = allCerts.filter((c) => c && c.portfolio !== false);

    // CV project blurbs can point at a full project with  id: '<project id>'  (content/cv.js)
    const blurbs = Array.isArray(cv.projects) ? cv.projects : [];
    const linked = new Map(blurbs.filter((b) => b.id).map((b) => [b.id, b]));
    const hiddenIds = new Set(allProjects.filter((p) => p && p.portfolio === false).map((p) => p.id));

    const master = {
        about: 'Generated by tools/build-pages.js from ' + SOURCES.join(', ') + '. Edit those files, not this one.',
        person: {
            name: clean(cv.name), title: clean(cv.title), tagline: clean(cv.tagline), location: clean(cv.location),
            phone: clean(cv.phone), linkedin: clean(cv.linkedin), website: SITE,
            portfolio: /^https:\/\//.test(cv.portfolio || '') ? cv.portfolio : SITE   // job-application portfolio, for letters and emails
        },
        summary: { id: 'summary-' + hash(cv.summary), text: clean(cv.summary) },
        experience: (cv.experience || []).map((x) => {
            const abbr = (x.org.match(/\(([A-Z][A-Za-z0-9 .]{1,12})\)/) || [])[1];   // "(KIRDI)" → kirdi
            const id = 'exp-' + slug(abbr || x.org.split(/[,(]/)[0], 18) + '-' + slug(x.role, 14);
            return { id, role: clean(x.role), org: clean(x.org), dates: clean(x.dates), year: latestYear(x.dates), points: lines(x.points, id) };
        }),
        projects: projects.map((p) => {
            const id = 'prj-' + slug(p.id, 30);
            const blurb = linked.get(p.id);
            const url = fs.existsSync(path.join(root, 'projects', p.id + '.html')) ? SITE + 'projects/' + p.id + '.html' : '';
            return {
                id, source: p.id, title: clean(p.title), subtitle: clean(p.subtitle), category: p.category === 'graphic' ? 'graphic' : 'engineering',
                year: clean(p.year), summary: clean(blurb ? blurb.text : p.summary), outcome: clean(p.outcome),
                points: lines(p.points, id), tags: (p.tags || []).map(clean).filter(Boolean),
                deliverables: (p.deliverables || []).map(clean).filter(Boolean), url
            };
        }),
        skills: lines(cv.skills, 'skill'),
        education: (cv.education || []).map((x) => ({ id: 'edu-' + slug(x.title, 20), title: clean(x.title), org: clean(x.org), dates: clean(x.dates), note: clean(x.note) })),
        certificates: certs.map((c) => ({ id: 'cert-' + slug(c.title, 22) + '-' + hash(c.title), title: clean(c.title), issuer: clean(c.issuer), kind: certKind(c), verify: /^https:\/\//.test(c.verify || '') ? c.verify : '' })),
        languages: (cv.languages || []).map(clean).filter(Boolean),
        memberships: (cv.memberships || []).map(clean).filter(Boolean),
        hidden: { projects: allProjects.length - projects.length, certificates: allCerts.length - certs.length }
    };

    // CV blurbs that don't point at a project on the site become projects of their own,
    // unless they point at a hidden one (then they stay hidden too)
    blurbs.filter((b) => !(b.id && (projects.some((p) => p.id === b.id) || hiddenIds.has(b.id)))).forEach((b) => {
        const id = 'prj-cv-' + slug(b.name, 26);
        master.projects.push({ id, source: 'content/cv.js', title: clean(b.name), subtitle: '', category: 'engineering', year: '', summary: clean(b.text), outcome: '', points: [], tags: [], deliverables: [], url: '' });
    });

    // Ids must be unique, or choices in the tailor would apply to two lines at once
    const seen = new Set();
    const all = [master.summary].concat(master.experience, master.experience.flatMap((x) => x.points), master.projects, master.projects.flatMap((p) => p.points), master.skills, master.education, master.certificates);
    for (const it of all) {
        let id = it.id, k = 2;
        while (seen.has(id)) id = it.id + '-' + k++;
        it.id = id;
        seen.add(id);
    }
    return master;
}

function masterJs(master) {
    return '/* Master CV for cv-tailor/: generated by tools/build-pages.js (see tools/cv-master.js).\n' +
        '   Edit content/cv.js, js/projects.js or the Google Sheet instead of this file.\n' +
        '   Projects and certificates marked portfolio: false are not in here. */\n' +
        'window.CV_MASTER = ' + JSON.stringify(master, null, 1) + ';\n';
}

module.exports = { buildMaster, masterJs, certKind, SOURCES };
