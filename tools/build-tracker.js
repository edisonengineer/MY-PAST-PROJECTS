#!/usr/bin/env node
/* =========================================================================
   Builds js/tracker-data.js for the client project tracker (/track/).
   Reads content/tracker.private.js (or the example if it doesn't exist),
   and encrypts every project with its own reference, so the published file
   reveals nothing unless you know a reference.

   Run:  node tools/build-tracker.js
   ========================================================================= */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const PRIVATE = path.join(ROOT, 'content/tracker.private.js');
const EXAMPLE = path.join(ROOT, 'content/tracker.example.js');
const OUT = path.join(ROOT, 'js/tracker-data.js');
const ITERATIONS = 150000;

const norm = (ref) => String(ref || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
const source = fs.existsSync(PRIVATE) ? PRIVATE : EXAMPLE;
const projects = require(source);

const seen = new Set();
const entries = projects.map((p) => {
    const ref = norm(p.ref);
    if (ref.length < 6) throw new Error('Reference too short: "' + p.ref + '" (use at least 6 letters/numbers)');
    if (seen.has(ref)) throw new Error('Duplicate reference: ' + p.ref);
    seen.add(ref);
    const salt = crypto.randomBytes(16);
    const iv = crypto.randomBytes(12);
    const key = crypto.pbkdf2Sync(ref, salt, ITERATIONS, 32, 'sha256');
    const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
    const data = Buffer.concat([cipher.update(JSON.stringify(Object.assign({}, p, { ref: p.ref })), 'utf8'), cipher.final(), cipher.getAuthTag()]);
    return {
        id: crypto.createHash('sha256').update('ncs-track:' + ref).digest('hex').slice(0, 24),
        s: salt.toString('base64'),
        i: iv.toString('base64'),
        d: data.toString('base64')
    };
});
// Shuffle so the order doesn't give anything away
entries.sort(() => Math.random() - 0.5);

fs.writeFileSync(OUT, '/* Generated by tools/build-tracker.js: encrypted, do not edit by hand. */\n' +
    'window.TRACKER = ' + JSON.stringify({ v: 1, n: ITERATIONS, items: entries }) + ';\n');
console.log('wrote js/tracker-data.js (' + entries.length + ' project' + (entries.length === 1 ? '' : 's') + ' from ' + path.relative(ROOT, source) + ')');
